using AntiScam.Application.DTOs.ScamScenario;
using AntiScam.Domain.Enums;

namespace AntiScam.Application.DTOs.Classification;

/// <summary>
/// Response returned after classifying a message for scam content.
/// </summary>
public sealed class ClassifyMessageResponse
{
    /// <summary>Gets or sets whether the classified content was detected as a scam.</summary>
    public bool IsScam { get; set; }

    /// <summary>Gets or sets the detected scam type enum value, if any.</summary>
    public ScamType? ScamType { get; set; }

    /// <summary>Gets or sets the human-readable scam type name (empty string when no scam).</summary>
    public string ScamTypeName { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the model's confidence score for its classification decision (0.0 – 1.0).
    /// </summary>
    public double Confidence { get; set; }

    /// <summary>
    /// Gets or sets the list of signals (keywords, patterns) that contributed to the classification.
    /// </summary>
    public List<string> MatchedSignals { get; set; } = new();

    /// <summary>Gets or sets actionable prevention advice for the user.</summary>
    public string PreventionAdvice { get; set; } = string.Empty;

    /// <summary>Gets or sets a list of scam scenarios related to the detected type.</summary>
    public List<ScamScenarioDto> RelatedScenarios { get; set; } = new();

    /// <summary>
    /// Gets or sets a legal/informational disclaimer about the accuracy and limitations of this classification.
    /// </summary>
    public string Disclaimer { get; set; } =
        "This classification is generated by an AI model and may not be fully accurate. " +
        "Always verify suspicious content through official channels before taking action.";
}
